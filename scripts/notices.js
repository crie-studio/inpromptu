function apacheText() {
  const candidates = ['node_modules/exponential-backoff/LICENSE', 'node_modules/flatbuffers/LICENSE'];
  for (const c of candidates) {
    const p = path.join(ROOT, c);
    if (fs.existsSync(p)) {
      const t = fs.readFileSync(p, 'utf8');
      const end = t.indexOf('END OF TERMS AND CONDITIONS');
      if (end > 0) return t.slice(0, end + 'END OF TERMS AND CONDITIONS'.length).trim();
    }
  }
  return 'See https://www.apache.org/licenses/LICENSE-2.0';
}

